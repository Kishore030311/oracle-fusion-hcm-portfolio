PAPF_ONE AS (
    SELECT PERSON_ID, PERSON_NUMBER
    FROM (
        SELECT PAPF.PERSON_ID, PAPF.PERSON_NUMBER,
               ROW_NUMBER() OVER (
                   PARTITION BY PAPF.PERSON_ID
                   ORDER BY PAPF.EFFECTIVE_START_DATE DESC, PAPF.PERSON_NUMBER
               ) AS RN
        FROM PER_ALL_PEOPLE_F PAPF
        WHERE TRUNC(SYSDATE) BETWEEN PAPF.EFFECTIVE_START_DATE AND PAPF.EFFECTIVE_END_DATE
    )
    WHERE RN = 1
),
HM_ALL AS (
    SELECT DISTINCT
           PAC.ALLOCATED_CHECKLIST_ID AS JOIN_CHECKLIST_ID
          ,REGEXP_SUBSTR(PAT.ATTRIBUTE14, '^[0-9]+') AS HM_PERSON_NUMBER
    FROM PER_ALLOCATED_CHECKLISTS PAC
          ,PER_ALLOCATED_TASKS_VL PAT
          ,PER_USERS PU
          ,PER_USER_ROLES PUR
          ,PER_ROLES_DN PRD
    WHERE (
                PAT.ALLOCATED_CHECKLIST_ID = PAC.ALLOCATED_CHECKLIST_ID
             OR PAT.ABS_ALLOCATED_CHECKLIST_ID = PAC.ALLOCATED_CHECKLIST_ID
           )
    AND PAT.TASK_PERFORMERS = PU.USER_GUID
    AND PU.USER_ID = PUR.USER_ID
    AND PUR.ROLE_ID = PRD.ROLE_ID
    AND PAT.TASK_NAME = '<TASK_NAME_POSITION_SELECTION>'
    AND PRD.ROLE_COMMON_NAME = '<HIRING_MANAGER_ROLE_NAME>'
),
