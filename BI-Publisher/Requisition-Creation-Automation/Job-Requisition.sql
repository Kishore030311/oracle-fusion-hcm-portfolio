/* ============================================================================
   JOBREQUISITION EXTRACT QUERY
   ----------------------------------------------------------------------------
   PURPOSE:
   Builds the JobRequisition HDL business object record from a completed
   Journey/Checklist. Run via HCM Extract; output is formatted by
   an e-Text template into a .dat file consumed by HCM Data Loader (HDL) to
   create Job Requisitions in Oracle Recruiting Cloud.

   SCOPE:
   Only processes checklists with CHECKLIST_STATUS = 'COM' for the journey
   identified by <CHECKLIST_ID>, and excludes any checklist already present
   in HRC_INTEGRATION_KEY_MAP (i.e., already loaded).

   PLACEHOLDERS TO REPLACE BEFORE USE:
     <CHECKLIST_ID>                  - target checklist/journey ID
     <TASK_NAME_TAM_1>               - TA Manager Alignment task name
     <TASK_NAME_TAM_2>               - TA Manager Approval task name
     <TASK_NAME_INTAKE_1..4>         - Intake Meeting Schedule task names
     <TASK_NAME_POSITION_SELECTION>  - Position Selection task name
     <TASK_NAME_JOB_DESC>            - Job Description/Position creation task name
     <UDT_USER_TABLE>                - UDT user table name for CSP lookup
     <UST_USER_COLUMN>               - UDT user column name for CSP lookup
     <SOURCE_SYSTEM_OWNER>           - HDL SOURCESYSTEMOWNER value
   ============================================================================ */

WITH
FUNCTION GET_DEPARTMENT_NAME(P_ORG_ID NUMBER) RETURN VARCHAR2 DETERMINISTIC AS
    LV_DEPT_NAME VARCHAR2(200);
BEGIN
    SELECT HAUFT_DEP.NAME
    INTO LV_DEPT_NAME
    FROM HR_ORG_UNIT_CLASSIFICATIONS_F HOUCF_DEP
          ,HR_ALL_ORGANIZATION_UNITS_F HAOUF_DEP
          ,HR_ORGANIZATION_UNITS_F_TL HAUFT_DEP
    WHERE HAOUF_DEP.ORGANIZATION_ID = HAUFT_DEP.ORGANIZATION_ID
    AND HAOUF_DEP.ORGANIZATION_ID = HOUCF_DEP.ORGANIZATION_ID
    AND HOUCF_DEP.CLASSIFICATION_CODE = 'DEPARTMENT'
    AND HOUCF_DEP.ORGANIZATION_ID = P_ORG_ID
    AND HAUFT_DEP.LANGUAGE = 'US'
    AND TRUNC(SYSDATE) BETWEEN HOUCF_DEP.EFFECTIVE_START_DATE AND HOUCF_DEP.EFFECTIVE_END_DATE
    AND TRUNC(SYSDATE) BETWEEN HAOUF_DEP.EFFECTIVE_START_DATE AND HAOUF_DEP.EFFECTIVE_END_DATE
    AND TRUNC(SYSDATE) BETWEEN HAUFT_DEP.EFFECTIVE_START_DATE AND HAUFT_DEP.EFFECTIVE_END_DATE;
    RETURN LV_DEPT_NAME;
EXCEPTION
    WHEN OTHERS THEN RETURN NULL;
END;
