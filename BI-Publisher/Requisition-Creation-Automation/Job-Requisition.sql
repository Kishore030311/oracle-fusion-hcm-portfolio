    AND PAAM.ASSIGNMENT_ID = PAC.ASSIGNMENT_ID
    AND TRUNC(SYSDATE) BETWEEN PAAM.EFFECTIVE_START_DATE AND PAAM.EFFECTIVE_END_DATE
    AND INT_ALL.JOIN_CHECKLIST_ID = PAC.ALLOCATED_CHECKLIST_ID
    AND (
            ( POS_ALL.ATTRIBUTE1 = 'Existing Position'
              AND EXISTS (
                    SELECT 1
                    FROM HR_ALL_POSITIONS_F_VL H2
                    WHERE H2.POSITION_CODE = TRIM(SUBSTR(POS_ALL.ATTRIBUTE2, INSTR(POS_ALL.ATTRIBUTE2, '-', -1) + 1))
                    AND TRUNC(SYSDATE) BETWEEN H2.EFFECTIVE_START_DATE AND H2.EFFECTIVE_END_DATE
                    AND EXISTS (SELECT 1 FROM FUN_ALL_BUSINESS_UNITS_V BUX WHERE BUX.BU_ID = H2.BUSINESS_UNIT_ID)
                  )
            )
         OR
            ( POS_ALL.ATTRIBUTE1 = 'New Position'
              AND EXISTS (SELECT 1 FROM FUN_ALL_BUSINESS_UNITS_V BUY WHERE BUY.BU_ID = PAAM.BUSINESS_UNIT_ID)
            )
        )
    AND NOT EXISTS (
        SELECT 1
        FROM HRC_INTEGRATION_KEY_MAP HIM
        WHERE HIM.OBJECT_NAME = 'Requisition'
        AND HIM.SOURCE_SYSTEM_ID = TO_CHAR(PAC.ALLOCATED_CHECKLIST_ID)
    )
),
REQNUM_MAP AS (
    SELECT ALLOCATED_CHECKLIST_ID
          ,(SELECT LATEST_NUM FROM LATEST_REQ)
             + ROW_NUMBER() OVER (ORDER BY ALLOCATED_CHECKLIST_ID) AS REQUISITIONNUMBER
    FROM REQNUM_BASE
),
MAIN_ROWS AS (
SELECT
     'JobRequisition' AS JOBREQUISITION
    ,'US' AS BASELANGUAGECODE
    ,RM.REQUISITIONNUMBER AS REQUISITIONNUMBER
    ,NVL(HM_ALL.HM_PERSON_NUMBER, PAPF.PERSON_NUMBER) AS HIRINGMANAGERPERSONNUMBER
    ,PAC.CHECKLIST_STATUS AS STATUS
    ,PAC.ALLOCATED_CHECKLIST_ID AS SOURCESYSTEMID
    ,'<SOURCE_SYSTEM_OWNER>' AS SOURCESYSTEMOWNER
    ,POS_ALL.ATTRIBUTE1 AS POSITION_SELECTION_TYPE
    ,DECODE(POS_ALL.ATTRIBUTE1,'New Position','ORA_NEW_POSITION','Existing Position','ORA_REPLACEMENT') AS BUSINESSJUSTIFICATION
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN TRIM(SUBSTR(POS_ALL.ATTRIBUTE2, 1, INSTR(POS_ALL.ATTRIBUTE2, '-', -1) - 1))
        WHEN 'New Position' THEN POS_ALL.ATTRIBUTE5
     END AS REQUISITIONTITLE
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN POS_ALL.ATTRIBUTE2
        WHEN 'New Position' THEN POS_ALL.ATTRIBUTE5
     END AS POSITION
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN TRIM(SUBSTR(POS_ALL.ATTRIBUTE2, INSTR(POS_ALL.ATTRIBUTE2, '-', -1) + 1))
        WHEN 'New Position' THEN JD_ALL.ATTRIBUTE1
     END AS POSITIONCODE
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN TO_CHAR(POS_ALL.ATTRIBUTE_NUMBER2)
        WHEN 'New Position' THEN TO_CHAR(POS_ALL.ATTRIBUTE_NUMBER1)
     END AS NUMBEROFOPENINGS
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN (
            SELECT BU2.BU_NAME
            FROM HR_ALL_POSITIONS_F_VL H2, FUN_ALL_BUSINESS_UNITS_V BU2
            WHERE H2.POSITION_CODE = TRIM(SUBSTR(POS_ALL.ATTRIBUTE2, INSTR(POS_ALL.ATTRIBUTE2, '-', -1) + 1))
            AND TRUNC(SYSDATE) BETWEEN H2.EFFECTIVE_START_DATE AND H2.EFFECTIVE_END_DATE
            AND BU2.BU_ID = H2.BUSINESS_UNIT_ID
            AND ROWNUM = 1
        )
        WHEN 'New Position' THEN GET_BU_BY_POSITION(JD_ALL.ATTRIBUTE1)
     END AS BUSINESSUNITSHORTCODE
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN GET_DEPARTMENT_NAME(PAAM.ORGANIZATION_ID)
        WHEN 'New Position' THEN POS_ALL.ATTRIBUTE7
     END AS DEPARTMENT
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN GET_DEPARTMENT_ORG_ID(PAAM.ORGANIZATION_ID)
        WHEN 'New Position' THEN GET_ORG_ID_BY_POSITION(JD_ALL.ATTRIBUTE1)
     END AS ORGANIZATIONID
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN GET_JOB_BY_JOB_ID(PAAM.JOB_ID)
        WHEN 'New Position' THEN GET_JOB_BY_POSITION(JD_ALL.ATTRIBUTE1)
     END AS JOB
    ,POS_ALL.ATTRIBUTE10 AS PRIMARYLOCATIONNAME
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN GET_GRADE_NAME(PAAM.GRADE_ID)
        WHEN 'New Position' THEN POS_ALL.ATTRIBUTE11
     END AS GRADE
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN
            GET_GRADE_CODE_BY_POSITION(
                TRIM(SUBSTR(POS_ALL.ATTRIBUTE2, INSTR(POS_ALL.ATTRIBUTE2, '-', -1) + 1))
            )
        WHEN 'New Position' THEN
            GET_GRADE_CODE_BY_POSITION(JD_ALL.ATTRIBUTE1)
     END AS GRADECODE
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN
            GET_JOB_CODE_BY_POSITION(
                TRIM(SUBSTR(POS_ALL.ATTRIBUTE2, INSTR(POS_ALL.ATTRIBUTE2, '-', -1) + 1))
            )
        WHEN 'New Position' THEN
            GET_JOB_CODE_BY_POSITION(JD_ALL.ATTRIBUTE1)
     END AS JOBCODE
    ,TRIM(SUBSTR(TAM_ALL.ATTRIBUTE1, INSTR(TAM_ALL.ATTRIBUTE1, '-') + 1)) AS RECRUITERPERSONNUMBER
    ,TAM_ALL.ATTRIBUTE2 AS COLLABORATOR1
    ,TAM_ALL.ATTRIBUTE3 AS COLLABORATOR2
    ,'REQUISITION_DRAFT' AS CURRENTPHASECODE
    ,'REQUISITION_IN_PROGRESS' AS CURRENTSTATECODE
    ,'Global Data Elements' AS "FLEX:IRC_REQUISITIONS_DFF"
    ,'N' AS UNLIMITEDOPENINGSFLAG
    ,'ORA_PROFESSIONAL' AS RECRUITINGTYPE
    ,'E' AS WORKERTYPE
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN
            GET_CSP(TRIM(SUBSTR(GET_GRADE_NAME(PAAM.GRADE_ID), 1,
                        CASE WHEN INSTR(GET_GRADE_NAME(PAAM.GRADE_ID), ' - ') > 0
                             THEN INSTR(GET_GRADE_NAME(PAAM.GRADE_ID), ' - ') - 1
                             ELSE LENGTH(GET_GRADE_NAME(PAAM.GRADE_ID))
                        END)))
        WHEN 'New Position' THEN
            GET_CSP(TRIM(SUBSTR(POS_ALL.ATTRIBUTE11, 1,
                        CASE WHEN INSTR(POS_ALL.ATTRIBUTE11, ' - ') > 0
                             THEN INSTR(POS_ALL.ATTRIBUTE11, ' - ') - 1
                             ELSE LENGTH(POS_ALL.ATTRIBUTE11)
                        END)))
     END AS CANDIDATESELECTIONPROCESSCODE
    ,GET_LEGAL_EMPLOYER(PAAM.ASSIGNMENT_ID) AS LEGALEMPLOYERNAME
    ,CASE POS_ALL.ATTRIBUTE1
        WHEN 'Existing Position' THEN GET_COST_CENTER_BY_ORG_ID(PAAM.ORGANIZATION_ID)
        WHEN 'New Position' THEN GET_COST_CENTER_BY_DEPT_NAME(POS_ALL.ATTRIBUTE7)
     END AS COSTCENTER
    ,POS_ALL.ATTRIBUTE4 AS NATIONALITYTYPE
    ,POS_ALL.ATTRIBUTE13 AS NUMBERWORKINGDAYSPERWEEK
    ,POS_ALL.TASK_COMMENTS AS COMMENTSJUSTIFICATION
    ,POS_ALL.ATTRIBUTE15 AS CONTRACTTERM
    ,POS_ALL.ATTRIBUTE16 AS LOCATIONTYPE
    ,TO_CHAR(POS_ALL.ATTRIBUTE_NUMBER1) AS DURATIONOFREQUIREMENTINYEAR
FROM
     PER_ALLOCATED_CHECKLISTS PAC
    JOIN PAPF_ONE PAPF
      ON PAPF.PERSON_ID = PAC.PERSON_ID
    JOIN POS_ALL
      ON POS_ALL.JOIN_CHECKLIST_ID = PAC.ALLOCATED_CHECKLIST_ID
    JOIN TAM_ALL
      ON TAM_ALL.JOIN_CHECKLIST_ID = PAC.ALLOCATED_CHECKLIST_ID
    JOIN PER_ALL_ASSIGNMENTS_M PAAM
      ON PAAM.ASSIGNMENT_ID = PAC.ASSIGNMENT_ID
     AND TRUNC(SYSDATE) BETWEEN PAAM.EFFECTIVE_START_DATE AND PAAM.EFFECTIVE_END_DATE
    JOIN INT_ALL
      ON INT_ALL.JOIN_CHECKLIST_ID = PAC.ALLOCATED_CHECKLIST_ID
    LEFT JOIN JD_ALL
      ON JD_ALL.JOIN_CHECKLIST_ID = PAC.ALLOCATED_CHECKLIST_ID
    LEFT JOIN REQNUM_MAP RM
      ON RM.ALLOCATED_CHECKLIST_ID = PAC.ALLOCATED_CHECKLIST_ID
    LEFT JOIN HM_ALL
      ON HM_ALL.JOIN_CHECKLIST_ID = PAC.ALLOCATED_CHECKLIST_ID
WHERE 1=1
    AND PAC.CHECKLIST_ID = '<CHECKLIST_ID>'
    AND PAC.CHECKLIST_STATUS = 'COM'
    AND (
            ( POS_ALL.ATTRIBUTE1 = 'Existing Position'
              AND EXISTS (
                    SELECT 1
                    FROM HR_ALL_POSITIONS_F_VL H2
                    WHERE H2.POSITION_CODE = TRIM(SUBSTR(POS_ALL.ATTRIBUTE2, INSTR(POS_ALL.ATTRIBUTE2, '-', -1) + 1))
                    AND TRUNC(SYSDATE) BETWEEN H2.EFFECTIVE_START_DATE AND H2.EFFECTIVE_END_DATE
                    AND EXISTS (SELECT 1 FROM FUN_ALL_BUSINESS_UNITS_V BUX WHERE BUX.BU_ID = H2.BUSINESS_UNIT_ID)
                  )
            )
         OR
            ( POS_ALL.ATTRIBUTE1 = 'New Position'
              AND EXISTS (SELECT 1 FROM FUN_ALL_BUSINESS_UNITS_V BUY WHERE BUY.BU_ID = PAAM.BUSINESS_UNIT_ID)
            )
        )
    /*AND (PAPF.PERSON_NUMBER = :P_PERSON_NUMBER OR :P_PERSON_NUMBER IS NULL)
    AND (PAC.ALLOCATED_CHECKLIST_ID = :P_ALLOCATED_CHECKLIST_ID OR :P_ALLOCATED_CHECKLIST_ID IS NULL)*/
    AND NOT EXISTS (
        SELECT 1
        FROM HRC_INTEGRATION_KEY_MAP HIM
        WHERE HIM.OBJECT_NAME = 'Requisition'
        AND HIM.SOURCE_SYSTEM_ID = TO_CHAR(PAC.ALLOCATED_CHECKLIST_ID)
    )
)
