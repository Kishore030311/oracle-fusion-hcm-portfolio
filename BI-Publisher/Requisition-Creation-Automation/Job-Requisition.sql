FUNCTION GET_COST_CENTER_BY_ORG_ID(P_ORG_ID NUMBER) RETURN VARCHAR2 DETERMINISTIC AS
    LV_COST_CENTER VARCHAR2(200);
BEGIN
    SELECT PCAA.SEGMENT1 || '-' || PCAA.SEGMENT2
    INTO LV_COST_CENTER
    FROM PAY_COST_ALLOC_ACCOUNTS PCAA
          ,PAY_COST_ALLOCATIONS_F PCAF
          ,HR_ALL_ORGANIZATION_UNITS_F HAOUF_LE
          ,HR_ORGANIZATION_UNITS_F_TL HAUFT_LE
          ,HR_ORG_UNIT_CLASSIFICATIONS_F HOUCF_DEP
          ,HR_ALL_ORGANIZATION_UNITS_F HAOUF_DEP
          ,HR_ORGANIZATION_UNITS_F_TL HAUFT_DEP
    WHERE PCAA.COST_ALLOCATION_RECORD_ID = PCAF.COST_ALLOCATION_RECORD_ID
    AND PCAA.SOURCE_SUB_TYPE = 'COST'
    AND PCAF.SOURCE_ID = HAOUF_LE.ORGANIZATION_ID
    AND HAOUF_LE.ORGANIZATION_ID = HAUFT_LE.ORGANIZATION_ID
    AND HAUFT_LE.LANGUAGE = 'US'
    AND TRUNC(SYSDATE) BETWEEN HAOUF_LE.EFFECTIVE_START_DATE AND HAOUF_LE.EFFECTIVE_END_DATE
    AND TRUNC(SYSDATE) BETWEEN HAUFT_LE.EFFECTIVE_START_DATE AND HAUFT_LE.EFFECTIVE_END_DATE
    AND TRUNC(SYSDATE) BETWEEN PCAF.EFFECTIVE_START_DATE AND PCAF.EFFECTIVE_END_DATE
    AND HAOUF_DEP.ORGANIZATION_ID = HAUFT_DEP.ORGANIZATION_ID
    AND HAOUF_DEP.ORGANIZATION_ID = HOUCF_DEP.ORGANIZATION_ID
    AND HOUCF_DEP.CLASSIFICATION_CODE = 'DEPARTMENT'
    AND HOUCF_DEP.ORGANIZATION_ID = P_ORG_ID
    AND HAUFT_DEP.LANGUAGE = 'US'
    AND TRUNC(SYSDATE) BETWEEN HOUCF_DEP.EFFECTIVE_START_DATE AND HOUCF_DEP.EFFECTIVE_END_DATE
    AND TRUNC(SYSDATE) BETWEEN HAOUF_DEP.EFFECTIVE_START_DATE AND HAOUF_DEP.EFFECTIVE_END_DATE
    AND TRUNC(SYSDATE) BETWEEN HAUFT_DEP.EFFECTIVE_START_DATE AND HAUFT_DEP.EFFECTIVE_END_DATE
    AND HAUFT_LE.NAME = HAUFT_DEP.NAME
    AND ROWNUM = 1;
    RETURN LV_COST_CENTER;
EXCEPTION
    WHEN OTHERS THEN RETURN NULL;
END;
