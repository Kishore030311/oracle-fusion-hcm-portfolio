     JOBREQUISITION
    ,BASELANGUAGECODE
    ,REQUISITIONNUMBER
    ,HIRINGMANAGERPERSONNUMBER
    ,STATUS
    ,SOURCESYSTEMID
    ,SOURCESYSTEMOWNER
    ,POSITION_SELECTION_TYPE
    ,REQUISITIONTITLE
    ,POSITION
    ,POSITIONCODE
    ,NUMBEROFOPENINGS
    ,BUSINESSUNITSHORTCODE
    ,DEPARTMENT
    ,ORGANIZATIONID
    ,JOB
    ,BUSINESSJUSTIFICATION
    ,PRIMARYLOCATIONNAME
    ,GRADE
    ,GRADECODE
    ,JOBCODE
    ,RECRUITERPERSONNUMBER
    ,COLLABORATOR1
    ,COLLABORATOR2
    ,CURRENTPHASECODE
    ,CURRENTSTATECODE
    ,"FLEX:IRC_REQUISITIONS_DFF"
    ,UNLIMITEDOPENINGSFLAG
    ,RECRUITINGTYPE
    ,WORKERTYPE
    ,CANDIDATESELECTIONPROCESSCODE
    ,LEGALEMPLOYERNAME
    ,COSTCENTER
    ,NATIONALITYTYPE
    ,NUMBERWORKINGDAYSPERWEEK
    ,COMMENTSJUSTIFICATION
    ,CONTRACTTERM
    ,LOCATIONTYPE
    ,DURATIONOFREQUIREMENTINYEAR
